package io.zenwave360.language.docs

import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertFalse
import kotlin.test.assertTrue
import kotlin.test.fail

/** [DslDocs.previewZdl]: one page for one ZDL document. */
class PreviewZdlTest {

    private val ordersCheckout = readTestFile("arcadia-editions/orders-checkout-api/domain-model.zdl")
    private val modulithOrders = readTestFile("arcadia-editions-modulith/orders-checkout-domain-model.zdl")
    private val hostile = "<script>alert(1)</script> <img src=http://evil.test/x.png onerror=alert(2)> ![pic](http://evil.test/y.png) " +
        "[link](https://evil.test/z) ![ref][r] <https://evil.test/auto> ```"

    private fun preview(text: String) = DslDocs().previewZdl(text)

    /** The page without its fenced code blocks, where only the generator and the escaped user text write. */
    private fun prose(page: String) = page.split("```mermaid\n").mapIndexed { i, part -> if (i == 0) part else part.substringAfter("\n```\n") }.joinToString("")

    @Test
    fun matchesTheSnapshot() {
        val page = preview(ordersCheckout)
        val snapshot = "snapshots/preview/orders-checkout.md"
        if (updateSnapshot(snapshot, page)) return
        val expected = try {
            readTestFile(snapshot)
        } catch (e: Throwable) {
            fail("Missing snapshot $snapshot. Run the JVM tests with DSL_DOCS_UPDATE_SNAPSHOTS=true to create it.")
        }
        assertEquals(expected, page)
    }

    @Test
    fun hasTheSectionsOfTheDomainPageThatComeFromOneDocument() {
        val page = preview(ordersCheckout)

        assertTrue(page.startsWith("# Arcadia Editions - Orders Checkout\n"), page.take(80))
        for (heading in listOf("## Contents", "## Services", "## Aggregates", "## Domain events", "## Commands", "## Glossary")) {
            assertTrue(page.contains("\n$heading\n"), heading)
        }
        assertTrue(page.contains("\nclassDiagram\n"))
        assertFalse(page.contains("## Architecture"))
        assertTrue(page.contains("```mermaid\n"))
    }

    @Test
    fun onlyApisLinkOutsideThePage() {
        for (zdl in listOf(ordersCheckout) + arcadiaModulith().map { it.content }) {
            val page = preview(zdl)
            val links = Regex("\\]\\(([^)]*)\\)").findAll(page).map { it.groupValues[1] }.toList()

            assertTrue(links.isNotEmpty())
            assertTrue(links.all { it.startsWith("#") || it.startsWith(".") || it.startsWith("http://") || it.startsWith("https://") }, links.filterNot { it.startsWith("#") || it.startsWith(".") || it.startsWith("http://") || it.startsWith("https://") }.toString())
            assertFalse(page.contains("Generated by dsl-docs"))
            assertFalse(page.contains("sha256"))
            assertFalse(page.contains("Source:"))
            assertFalse(page.contains("Back to"))
        }
    }

    @Test
    fun listsApisAndPoliciesIncludingUnassignedPolicies() {
        val page = preview(
            """
            apis {
                openapi provider OrdersApi "./orders.yml"
                asyncapi client EventsApi "https://example.test/events.yml"
                zdl client SharedModel "../shared/model.zdl"
            }
            @aggregate
            entity Order { id UUID }
            @aggregate
            entity Customer { id UUID }
            policies (Order) { orderNumberUnique "Order numbers are unique" }
            policies { audit "Every change is audited" }
            """.trimIndent(),
        )

        assertTrue(page.indexOf("## Contents") < page.indexOf("## APIs"), page)
        assertTrue(page.contains("| API | Kind | Role | Location |"), page)
        assertTrue(page.contains("[./orders.yml](./orders.yml)"), page)
        assertTrue(page.contains("[https\\://example.test/events.yml](https://example.test/events.yml)"), page)
        assertTrue(page.contains("audit: Every change is audited\n\n### Order\n\norderNumberUnique: Order numbers are unique\n\n```mermaid"), page)
        assertFalse(page.contains("### Customer\n\norderNumberUnique"), page)

        val noApis = preview("@aggregate\nentity Invoice { id UUID }")
        assertFalse(noApis.contains("## APIs"), noApis)
    }

    @Test
    fun severalPoliciesEachGetTheirOwnLine() {
        val page = preview(
            """
            @aggregate
            entity Order { id UUID }
            policies (Order) {
                first "First rule"
                second "Second rule"
            }
            policies {
                alpha "Alpha rule"
                beta "Beta rule"
            }
            """.trimIndent(),
        )

        assertTrue(page.contains("alpha: Alpha rule  \nbeta: Beta rule\n\n### Order"), page)
        assertTrue(page.contains("first: First rule  \nsecond: Second rule\n\n```mermaid"), page)
    }

    @Test
    fun apiLocationsThatAreNotWorkspaceOrHttpLinksStayText() {
        val page = preview(
            """
            apis {
                openapi provider SafeApi "api/openapi.yml"
                asyncapi client HostileApi "javascript:alert(1) [injected](https://evil.test)"
            }
            """.trimIndent(),
        )

        assertTrue(page.contains("[api/openapi.yml](api/openapi.yml)"), page)
        assertTrue(page.contains("javascript:alert(1) \\[injected\\](https\\://evil.test)"), page)
        assertFalse(Regex("(?<!\\\\)\\]\\(https?://evil", RegexOption.IGNORE_CASE).containsMatchIn(page), page)
        assertFalse(page.contains("no services, entities or events"), page)
    }

    @Test
    fun everySameFileLinkHasItsHeading() {
        val page = preview(ordersCheckout)
        val headings = Regex("^#{1,6} (.+)$", RegexOption.MULTILINE).findAll(page).map { it.groupValues[1] }.toList()
        val anchors = io.zenwave360.language.docs.internal.Anchors.slugs(headings).toSet()

        for (anchor in Regex("\\]\\(#([^)]*)\\)").findAll(page).map { it.groupValues[1] }) {
            assertTrue(anchor in anchors, "no heading for #$anchor")
        }
    }

    @Test
    fun descriptionsCannotBringScriptImagesOrRemoteReferences() {
        val zdl = modulithOrders.replace("Customer snapshot taken at checkout (there is no customers bounded context yet).", hostile)
        assertTrue(zdl != modulithOrders)

        val page = preview(zdl)

        assertTrue(page.contains("&lt;script&gt;alert(1)&lt;/script&gt;"), "shown as text")
        assertTrue(page.contains("&lt;img src=http\\://evil.test/x.png"), "shown as text")
        assertFalse(page.contains("<script"))
        assertFalse(page.contains("<img"))
        assertTrue(page.contains("!\\[pic\\](http\\://evil.test/y.png)"), "the image shows as text")
        assertFalse(page.contains("!["))
        assertFalse(Regex("(?<!\\\\)\\]\\(http").containsMatchIn(page), "a link or image to a remote URL")
        assertFalse(page.contains("[link]"))
        assertFalse(Regex("(?<!\\\\)://").containsMatchIn(page), "an unescaped URL")
        assertFalse(page.contains("<https"))
        assertFalse(Regex("https?://", RegexOption.IGNORE_CASE).containsMatchIn(page))
        // The user's text stays out of the fenced blocks, so it cannot close one.
        assertEquals(preview(modulithOrders).split("```mermaid\n").size, page.split("```mermaid\n").size)
        assertFalse(page.substringAfter("```mermaid\n").split("\n```\n").first().contains("evil"))
        assertEquals(page.split("\n").count { it.startsWith("```mermaid") }, page.split("\n").count { it == "```" })
    }

    @Test
    fun hostileTextInOtherPlacesIsEscaped() {
        val zdl = """
            config { title "<script>alert(1)</script>" }
            /** ![x](http://evil.test/a.png) <iframe src=http://evil.test></iframe> */
            entity Order { /** <img src=http://evil.test/b> */ name String }
            /** [a](http://evil.test) */
            enum Kind { A /** <script>x</script> */, B }
        """.trimIndent()

        val page = preview(zdl)

        assertFalse(Regex("<script|<img|<iframe|!\\[|(?<!\\\\)\\]\\(http|https?://", RegexOption.IGNORE_CASE).containsMatchIn(page), page)
        assertTrue(page.contains("\nclassDiagram\n"))
    }

    @Test
    fun semanticProblemsStillGiveThePage() {
        val zdl = """
            entity Order { customer Customer }
            service OrderService for (Missing) { create(Order) Order withEvents UnknownEvent }
        """.trimIndent()

        val page = preview(zdl)

        assertTrue(page.contains("\nclassDiagram\n"), page)
        assertTrue(page.contains("## Glossary"), page)
    }

    @Test
    fun syntaxErrorGivesAPageWithTheProblems() {
        val page = preview("entity Order { name String \n entity")

        assertTrue(page.contains("> **Problems**"), page)
        assertTrue(page.contains("line "), page)
        assertTrue(page.contains("\nclassDiagram\n"), page)
    }

    @Test
    fun aDocumentWithoutEntitiesOrCommandsGivesASensiblePage() {
        for (zdl in listOf("", "   \n", "config { title \"Only config\" }", "enum Kind { A, B }")) {
            val page = preview(zdl)

            assertTrue(page.startsWith("# "), zdl)
            assertFalse(page.contains("null"), page)
        }
        assertTrue(preview("").contains("no services, entities or events"))
        assertTrue(preview("config { title \"Only config\" }").startsWith("# Only config\n"))
        assertTrue(preview("enum Kind { A, B }").contains("#### Kind"))
    }

    @Test
    fun isDeterministicAndIndependentOfLineEndings() {
        val crlf = ordersCheckout.replace("\n", "\r\n")

        assertEquals(preview(ordersCheckout), preview(ordersCheckout))
        assertEquals(preview(ordersCheckout), preview(crlf))
    }

    @Test
    fun generateIsNotAffected() {
        val before = DslDocs().generate(DocsInput(arcadiaOrdersCheckout()))
        preview(ordersCheckout)
        assertEquals(before, DslDocs().generate(DocsInput(arcadiaOrdersCheckout())))
    }

    @Test
    fun timeOnTheLargestFixture() {
        val zdl = arcadiaModulith().maxByOrNull { it.content.length }!!
        preview(zdl.content)
        val start = kotlin.time.TimeSource.Monotonic.markNow()
        repeat(10) { preview(zdl.content) }
        println("PREVIEW-TIMING ${zdl.path} (${zdl.content.length} chars): ${start.elapsedNow() / 10} per preview")
    }
}
